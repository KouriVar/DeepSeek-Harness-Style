import path from 'node:path';
import { scan } from './lib/scan.mjs';
import { indexQoder,recommend,selectPilot,coverage } from './lib/match.mjs';
import {LOCAL,writeJSON} from './lib/common.mjs';
import {reports} from './lib/report.mjs';
console.log('1/4 扫描本机 DSH 发行代码与已安装插件…');
const {inventory,report}=scan();
console.log(`识别 ${inventory.length} 个语义记录，${report.resolved} 个预览；待检查 ${report.unresolved}。`);
console.log('2/4 校验已有 Qoder 资源并建立索引，不复制完整素材…');
const {pack,icons}=await indexQoder();
console.log(`索引 ${icons.length} 个 SVG（${pack.namedIcons} 命名 + ${pack.customIcons} 变体）。`);
console.log('3/4 运行本地语义与几何候选匹配…');
const candidates=await recommend(inventory,icons);
console.log('4/4 选择第一轮 30 个真实用例并生成覆盖率…');
const pilot=selectPilot(inventory,candidates);
const stats=reports({inventory,icons,pack,report,pilot,candidates});
writeJSON(path.join(LOCAL,'data/coverage.json'),stats);
writeJSON(path.join(LOCAL,'data/index-version.json'),{schemaVersion:1,generatedAt:new Date().toISOString(),dshVersion:report.dshVersion,pack,pilotCount:pilot.items.length});
console.log(JSON.stringify({coverage:stats,pilot:pilot.items.length,missingPilotRoles:pilot.missingRequestedRoles},null,2));
